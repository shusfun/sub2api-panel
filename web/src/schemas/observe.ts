import {z} from "zod";
import {id, instant, page, tokenCount} from "./common";

const usageTokens = z.object({
  input_tokens: tokenCount,
  output_tokens: tokenCount,
  cache_read_tokens: tokenCount,
  cache_creation_tokens: tokenCount,
});
const usageDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/);
const usageModel = z.object({model: z.string(), requests: tokenCount, total_tokens: tokenCount, actual_cost: z.number().finite()});
const usageBucket = usageTokens.extend({
  start: instant,
  end: instant,
  pending: z.boolean().optional(),
  requests: tokenCount,
  actual_cost: z.number().finite(),
});

export const usage = z.object({
  id,
  model: z.string(),
  created_at: z.string(),
  input_tokens: z.number(),
  output_tokens: z.number(),
  actual_cost: z.number().nullable(),
});

export const usageRecord = usage.extend({
  created_at: z.string().datetime({offset: true}),
  key_name: z.string(),
  input_tokens: tokenCount,
  output_tokens: tokenCount,
  cache_read_tokens: tokenCount.nullable(),
  cache_creation_tokens: tokenCount.nullable(),
  api_key_id: id.optional(),
  user_id: id.optional(),
  user_email: z.string().optional(),
  group_id: id.nullable().optional(),
  group_name: z.string().optional(),
  account_id: id.nullable().optional(),
  account_name: z.string().optional(),
  duration_ms: z.number().nullable().optional(),
  first_token_ms: z.number().nullable().optional(),
  stream: z.boolean().nullable().optional(),
});

export const usageSummary = z.object({
  timezone: z.string(),
  start_date: usageDate,
  end_date: usageDate,
  totals: usageTokens.extend({requests: tokenCount, actual_cost: z.number().finite()}),
  days: z.array(usageTokens.extend({date: usageDate, requests: tokenCount, actual_cost: z.number().finite()})).max(90),
  granularity: z.enum(["hour", "day"]),
  buckets: z.array(usageBucket).max(175),
  ranking: z.array(usageModel),
  model_series: z.object({
    ready_days: tokenCount,
    total_days: tokenCount,
    unavailable: z.boolean().optional(),
    buckets: z.array(z.object({start: instant, models: z.array(usageModel)})).max(175),
  }),
  models: page(usageModel),
});

export const usageStreamEvent = z.object({
  type: z.enum(["snapshot", "delta", "heartbeat", "unavailable"]),
  cursor: z.string().optional(),
  snapshot: usageSummary.optional(),
  delta: usageSummary.partial().optional(),
  base: z.string().optional(),
  request_id: z.string().optional(),
  reason: z.enum(["not_allowed", "upstream_error"]).optional(),
  server_time: instant,
});

